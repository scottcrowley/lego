<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Storage;

class CheckUserPartsCsv extends Command
{
    use CommandHelpers, CsvHelpers, CheckHelpers;

    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'lego:check-user-parts-csv
                            {--bulk : Command being run with other commands}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Verifies that all table dependencies are present from csv file generated by Rebrickable.';

    /**
     * CSV File Url
     *
     * @var string
     */
    protected $url = '';

    /**
     * CSV Column names
     *
     * @var array
     */
    protected $csvKeys;

    /**
     * Create a new command instance.
     *
     * @return void
     */
    public function __construct()
    {
        parent::__construct();

        $this->checkTables = [
            'parts' => ['part_num', 'part_num'],
            'colors' => ['id', 'color_id']
        ];

        $this->missingDeps = $this->loadedDeps = [
            'parts' => [],
            'colors' => []
        ];

        $this->csvKeys = [
            'Part',
            'Color',
            'Quantity'
        ];

        $this->keys = collect([
            'part_num',
            'color_id',
            'quantity'
        ]);

        $this->url = 'https://rebrickable.com/users/'.(config('rebrickable.api.username')).'/allparts/parts/?format=rbpartscsv&inc_spares=0&&';
    }

    /**
     * Execute the console command.
     *
     * @return mixed
     */
    public function handle()
    {
        if (! $this->start()) {
            return false;
        }

        if (! $this->option('bulk')) {
            $this->processStart = microtime(true);
        }

        $this->info('');
        $this->normalizeCsv();
        $this->getDependencies();
        // $this->checkDirectory();
        // $this->retrieveFile();
        // $this->displayCsvDate();
        $this->loadDependenciesFromCSV();
        $this->compileMissingDependencies();
        $this->cleanUp();
        $this->displayMissing();
        if (! $this->option('bulk')) {
            $this->goodbye();
        }
        $this->displayProcessed();
    }

    /**
     * Display command details and request confirmation to continue
     *
     * @return bool
     */
    protected function start()
    {
        $this->info('>> Please wait while we verify all the dependencies are available for User Parts');
        $this->info('   Since the CSV file is located at a dynamic url, you will need to download the file');
        $this->info('   manually from '.$this->url);
        $this->info('   rename it "rebrickable.csv" and place the file in /storage/app/csv_files.');
        return $this->confirm('The process will not be able to complete without this file in that location. Continue?');
    }

    /**
     * Update the 1st line of the downloaded csv with the columns name instead of the column labels
     *
     * @return void
     */
    protected function normalizeCsv()
    {
        Storage::move('csv_files/rebrickable.csv', 'csv_files/rebrickable_copy.csv');

        $original = fopen(storage_path('app/csv_files/rebrickable_copy.csv'), 'r');
        if (! is_resource($original)) {
            die('Failed to open the source file');
        }

        $new = fopen(storage_path('app/csv_files/rebrickable.csv'), 'w');
        if (! is_resource($new)) {
            die('Failed to open to destination file');
        }

        $data = [];
        $data[] = fgetcsv($original);

        if ($data[0] != $this->csvKeys) {
            array_unshift($data, $this->csvKeys);
        } else {
            $data[0] = $this->keys->toArray();
        }

        while (($line = fgetcsv($original)) !== false) {
            $data[] = $line;
        }

        foreach ($data as $row) {
            fputcsv($new, $row);
        }

        fclose($original);
        fclose($new);

        return true;
    }

    /**
     * Delete the downloaded csv file
     *
     * @return void
     */
    protected function cleanUp()
    {
        Storage::delete('csv_files/rebrickable.csv');
        Storage::move('csv_files/rebrickable_copy.csv', 'csv_files/rebrickable.csv');
    }
}
